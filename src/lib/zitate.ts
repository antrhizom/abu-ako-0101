/** Zitat einer Monade: eigenes, sonst eines aus der Reihe nach Seed */
export function zitatFuer(key: string | undefined, seed: number): Zitat {
  if (key && zitate[key]) return zitate[key];
  return zitate[reihe[seed % reihe.length]];
}
